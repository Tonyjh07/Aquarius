package main

import (
	"bytes"
	"errors"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/Tonyjh07/Aquarius/assets"
	"github.com/Tonyjh07/Aquarius/internal/adapter/atomicfile"
	"github.com/Tonyjh07/Aquarius/internal/logging"
)

// dataReadmeName 数据目录说明的文件名。只放数据根一份，profiles/<name>/ 不各写一份——
// 切过 profile 的机器上会留下多份版本不一的副本，读者不知道信哪份（D291 决策 1）。
const dataReadmeName = "README.md"

// dataReadmeMarker 生成文件的身份证：首行以此开头才允许覆盖。用户把自己的笔记写在
// 这份文件上之后，改掉这一行就等于贴了「别动」的条子——程序保留原样，只记一行日志
// （D291 决策 5）。
const dataReadmeMarker = "<!-- generated by Aquarius"

// dataReadmeOutcome 一次「确保说明存在」的结果，与日志一一对应。
type dataReadmeOutcome int

const (
	readmeCreated   dataReadmeOutcome = iota // 之前没有，这次写了
	readmeUpdated                            // 有生成标记，内容或版本变了，重写
	readmeUnchanged                          // 逐字节相同，连 mtime 都不动
	readmeKept                               // 没有生成标记：是用户自己写的，不碰
	readmeFailed                             // 读或写失败
)

// renderDataReadme 拼出整份文件：首行模板（注入版本号）+ 中文正文 + 英文正文。
//
// 首行只放版本号，不放时间戳。放了时间，「内容没变」就永不成立，每次启动都要重写一遍
// （D291 决策 4）。三段正文都走 go:embed，缘由同 internal/legal：正文是给人读的
// Markdown，改一句要能在 diff 里看见；落盘内容两种语言同时出现，进 i18n 表只会取到
// 其中一种，所以这三段不经过取词口。
func renderDataReadme(version string) []byte {
	ver := strings.TrimSpace(version)
	if ver == "" {
		ver = "dev"
	}
	var b bytes.Buffer
	b.WriteString(strings.ReplaceAll(string(assets.DataReadmeHeader), "{version}", ver))
	b.WriteString("\n")
	b.Write(assets.DataReadmeZH)
	b.WriteString("\n---\n\n")
	b.Write(assets.DataReadmeEN)
	return b.Bytes()
}

// ensureDataReadme 按四态处理数据根下那份说明（D291 决策 5）：不存在就写；逐字节相同
// 不动；有生成标记就重写；没有标记就保留。返回的 error 只在 Failed 时有意义。
func ensureDataReadme(dir, version string) (dataReadmeOutcome, error) {
	path := filepath.Join(dir, dataReadmeName)
	want := renderDataReadme(version)
	old, err := os.ReadFile(path)
	switch {
	case err == nil:
		if bytes.Equal(old, want) {
			return readmeUnchanged, nil
		}
		if !bytes.HasPrefix(old, []byte(dataReadmeMarker)) {
			return readmeKept, nil
		}
		if werr := atomicfile.WriteFile(path, want, 0o644); werr != nil {
			return readmeFailed, werr
		}
		return readmeUpdated, nil
	case errors.Is(err, fs.ErrNotExist):
		if werr := atomicfile.WriteFile(path, want, 0o644); werr != nil {
			return readmeFailed, werr
		}
		return readmeCreated, nil
	default:
		return readmeFailed, err
	}
}

// writeDataReadme 在启动期把说明落到数据根。写不出来只记一行 warn，不拦启动：这是给
// 人看的手册，缺了不影响程序干活（D291 决策 6）。
func (w *wiring) writeDataReadme() {
	path := filepath.Join(w.dir, dataReadmeName)
	out, err := ensureDataReadme(w.dir, version)
	switch out {
	case readmeCreated, readmeUpdated:
		w.note(logging.LevelInfo, logging.Boot, "log.boot.readme_written",
			"log.act.readme_written", "path", path)
	case readmeKept:
		w.note(logging.LevelWarn, logging.Boot, "log.boot.readme_kept",
			"log.act.readme_kept", "path", path)
	case readmeFailed:
		w.note(logging.LevelWarn, logging.Boot, "log.boot.readme_failed",
			"log.act.continue", "path", path, "err", err)
	}
}
