package main

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// hookMarker 认领标记：有它说明这个 hook 是本程序生成的，可以安全覆盖。
const hookMarker = "generated by cmd/ci"

// prePushHook 推送前跑 fast 档。只有这一档适合放进 hook——它必须快到
// 让人愿意等；default 与 full 靠人手动跑，跑完的结果记在证据文件里。
const prePushHook = `#!/bin/sh
# ` + hookMarker + ` --install-hooks；要改内容请改源码后重新生成，别手改这一份。
cd "$(git rev-parse --show-toplevel)" || exit 1
exec go run ./cmd/ci --profile=fast
`

// installPrePush 把 pre-push hook 写进仓库。用 --git-path 取路径，
// worktree 与 submodule 下也对。
func installPrePush(root string) error {
	dir, err := hooksDir(root)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	path := filepath.Join(dir, "pre-push")

	if old, err := os.ReadFile(path); err == nil && !strings.Contains(string(old), hookMarker) {
		// 已有别人写的 hook：留一份备份再覆盖，不静默丢掉。
		if err := os.WriteFile(path+".bak", old, 0o644); err != nil {
			return fmt.Errorf("备份原有 hook 失败：%w", err)
		}
		fmt.Printf("原有 pre-push 已备份为 %s.bak\n", path)
	}
	if err := os.WriteFile(path, []byte(prePushHook), 0o755); err != nil {
		return err
	}
	fmt.Printf("已安装 %s：推送前跑 fast 档（gofmt / 文档标记 / vet）\n", path)
	return nil
}

func hooksDir(root string) (string, error) {
	out, err := exec.Command("git", "-C", root, "rev-parse", "--git-path", "hooks").Output()
	if err != nil {
		return "", fmt.Errorf("定位 hooks 目录失败：%w", err)
	}
	p := strings.TrimSpace(string(out))
	if p == "" {
		return "", fmt.Errorf("git 没有返回 hooks 目录")
	}
	if !filepath.IsAbs(p) {
		p = filepath.Join(root, p)
	}
	return filepath.Clean(p), nil
}
