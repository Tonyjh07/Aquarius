//  2. **文案不写在这**。事件与行动都是 key，正文在 `internal/i18n` 的 `log.*` 段；本包只负责
//     字段、过滤、切分与渲染，出现任何用户面字符串都是走错了地方。
//  3. **写失败静默**。日志不得打断对话：打不开文件就退化成只写 stderr，写不进去就丢掉这一行。
